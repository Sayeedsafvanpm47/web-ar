import { headers } from 'next/headers';
import Link from 'next/link';
import { notFound } from 'next/navigation';

import { requireStaff } from '@/lib/auth';
import { bookUrl, memoryUrl, qrSvg } from '@/lib/qr';
import { createClient } from '@/lib/supabase/server';

export const metadata = { title: 'Print files' };

/**
 * The QR codes that go into a printed book.
 *
 * One for the cover, which opens the book, and one per page, which plays that
 * page's video without the camera. The page QRs are the product's safety net:
 * if the camera path fails for any reason, the customer can still watch.
 *
 * Laid out to be printed directly from the browser. Staff can also right-click
 * any code and save the SVG.
 */
export default async function PrintPage({
  params,
}: {
  params: Promise<{ bookId: string }>;
}) {
  await requireStaff();
  const [{ bookId }, headerList] = await Promise.all([params, headers()]);

  const supabase = await createClient();

  const { data: book } = await supabase
    .from('books')
    .select('id, title, reference, customers(full_name)')
    .eq('id', bookId)
    .maybeSingle();

  if (!book) notFound();

  const { data: memoryData } = await supabase
    .from('memories')
    .select('id, target_index, page_label')
    .eq('book_id', bookId)
    .order('target_index');

  const memories = memoryData ?? [];

  // Prefer the deployed origin; fall back to the request's own host so print
  // files generated from a preview or locally still resolve.
  const origin =
    process.env.NEXT_PUBLIC_VIEWER_ORIGIN ??
    `https://${headerList.get('host') ?? 'localhost:3000'}`;

  const cover = await qrSvg(bookUrl(origin, book.id));
  const pages = await Promise.all(
    memories.map(async (m) => ({
      id: m.id as string,
      index: m.target_index as number,
      label: (m.page_label as string | null) ?? null,
      svg: await qrSvg(memoryUrl(origin, book.id, m.id as string)),
    })),
  );

  const reference = (book.reference as string | null) ?? null;

  return (
    <main className="mx-auto max-w-4xl space-y-8 p-6 print:p-0">
      <div className="print:hidden">
        <Link
          href={`/admin/books/${book.id}`}
          className="text-muted-foreground text-sm hover:underline"
        >
          ← {book.title as string}
        </Link>
        <h1 className="text-xl font-semibold">Print files</h1>
        <p className="text-muted-foreground mt-2 text-sm">
          Generated locally — these URLs are never sent to a third party.
          Print this page, or right-click any code to save the SVG.
        </p>
        <p className="mt-2 text-sm text-amber-700 dark:text-amber-400">
          Every code below opens this customer&apos;s videos. Treat the print
          files like the book itself: do not email them around or leave them in
          a shared folder.
        </p>
      </div>

      <section className="break-inside-avoid rounded-md border p-6">
        <p className="text-muted-foreground text-xs tracking-widest uppercase">
          Inside cover
        </p>
        <div className="mt-4 flex items-center gap-8">
          <div
            className="h-44 w-44 shrink-0"
            // Generated by the qrcode library from a URL we constructed; no
            // user-controlled markup reaches this.
            dangerouslySetInnerHTML={{ __html: cover }}
          />
          <div className="space-y-1">
            <p className="text-lg font-medium">{book.title as string}</p>
            <p className="text-muted-foreground text-sm">
              {(book.customers as unknown as { full_name: string } | null)
                ?.full_name ?? 'no customer'}
            </p>
            {reference ? (
              <p className="pt-2 font-mono text-sm">{reference}</p>
            ) : (
              <p className="pt-2 text-sm text-amber-700">
                No reference — apply the book reference migration.
              </p>
            )}
            <p className="text-muted-foreground text-xs">
              Print the reference beside the code. It is what the customer
              quotes to support, and unlike the link it grants no access.
            </p>
          </div>
        </div>
      </section>

      <section>
        <p className="text-muted-foreground mb-4 text-xs tracking-widest uppercase print:hidden">
          One per page · plays without the camera
        </p>
        <div className="grid grid-cols-2 gap-6 sm:grid-cols-3">
          {pages.map((p) => (
            <div
              key={p.id}
              className="break-inside-avoid rounded-md border p-4 text-center"
            >
              <div
                className="mx-auto h-32 w-32"
                dangerouslySetInnerHTML={{ __html: p.svg }}
              />
              <p className="mt-2 text-sm font-medium">Page {p.index + 1}</p>
              {p.label ? (
                <p className="text-muted-foreground text-xs">{p.label}</p>
              ) : null}
            </div>
          ))}
        </div>
        {pages.length === 0 ? (
          <p className="text-muted-foreground text-sm">
            No pages yet, so there are no page codes to print.
          </p>
        ) : null}
      </section>
    </main>
  );
}
